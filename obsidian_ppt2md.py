import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
import threading
from datetime import datetime
from pathlib import Path

MARKER = "<!-- generated by obsidian_pdf2md -->"
ATTACH_DIR_NAME = "attachments"
PPT_EXTS = {".ppt", ".pptx"}
MIN_EMBED_BYTES = 1024  # 小于该字节数的嵌入图片视为图标/装饰，忽略


def win_long_path(p: Path) -> Path:
    if os.name == "nt":
        s = str(p)
        if not s.startswith("\\\\?\\") and len(s) > 240:
            return Path("\\\\?\\" + s)
    return p


def log(msg: str) -> None:
    print(msg, flush=True)


def md_table(rows) -> str:
    """二维列表 -> Markdown 表格。"""
    if not rows:
        return ""
    ncols = max(len(r) for r in rows)
    rows = [list(r) + [""] * (ncols - len(r)) for r in rows]
    lines = ["| " + " | ".join(rows[0]) + " |", "| " + " | ".join(["---"] * ncols) + " |"]
    for r in rows[1:]:
        lines.append("| " + " | ".join(r) + " |")
    return "\n".join(lines)


# ---------- 整页渲染 ----------

def render_with_powerpoint(ppt_path: Path, att_dir: Path, stem: str, lock) -> int:
    """用 PowerPoint COM 将每页幻灯片导出为 PNG。返回渲染页数，失败返回 0。"""
    app = None
    try:
        import win32com.client
        import pythoncom

        pythoncom.CoInitialize()
        # DispatchEx 启动独立实例，避免关闭用户正在使用的 PowerPoint
        app = win32com.client.DispatchEx("PowerPoint.Application")
        pres = app.Presentations.Open(str(ppt_path), True, False, False)  # ReadOnly
        w = int(pres.PageSetup.SlideWidth) * 2
        h = int(pres.PageSetup.SlideHeight) * 2
        n = 0
        for i, slide in enumerate(pres.Slides, 1):
            fname = f"{stem}-slide-{i:02d}.png"
            slide.Export(str(att_dir / fname), "PNG", w, h)
            n += 1
        try:
            pres.Close()
        except Exception:
            pass
        with lock:
            log(f"[信息] 已用 PowerPoint 渲染 {n} 页幻灯片")
        return n
    except Exception as e:
        with lock:
            log(f"[警告] PowerPoint 渲染失败（{ppt_path.name}）：{e}")
        return 0
    finally:
        try:
            if app:
                app.Quit()
        except Exception:
            pass
        try:
            pythoncom.CoUninitialize()
        except Exception:
            pass


def find_soffice():
    for c in (r"C:\Program Files\LibreOffice\program\soffice.exe",
              r"C:\Program Files (x86)\LibreOffice\program\soffice.exe"):
        if os.path.isfile(c):
            return c
    for name in ("soffice", "soffice.exe"):
        p = shutil.which(name)
        if p:
            return p
    return None


def render_with_libreoffice(ppt_path: Path, att_dir: Path, stem: str, soffice: str, lock) -> int:
    """LibreOffice: PPT -> PDF -> 渲染每页为 PNG。返回渲染页数，失败返回 0。"""
    try:
        with tempfile.TemporaryDirectory() as td:
            r = subprocess.run(
                [soffice, "--headless", "--convert-to", "pdf", "--outdir", td, str(ppt_path)],
                capture_output=True, timeout=300,
            )
            pdf = Path(td) / (ppt_path.stem + ".pdf")
            if not pdf.exists():
                return 0
            try:
                import pymupdf as fitz
            except ImportError:
                try:
                    import fitz
                except ImportError:
                    return 0
            doc = fitz.open(pdf)
            n = 0
            for i, page in enumerate(doc, 1):
                pix = page.get_pixmap(matrix=fitz.Matrix(2, 2), alpha=False)
                fname = f"{stem}-slide-{i:02d}.png"
                pix.save(str(att_dir / fname))
                n += 1
            doc.close()
        with lock:
            log(f"[信息] 已用 LibreOffice 渲染 {n} 页幻灯片")
        return n
    except Exception as e:
        with lock:
            log(f"[警告] LibreOffice 渲染失败（{ppt_path.name}）：{e}")
        return 0


def render_slides(ppt_path: Path, att_dir: Path, lock) -> int:
    """渲染每页幻灯片为 PNG；依次尝试 PowerPoint -> LibreOffice。"""
    stem = ppt_path.stem
    n = render_with_powerpoint(ppt_path, att_dir, stem, lock)
    if n:
        return n
    soffice = find_soffice()
    if soffice:
        return render_with_libreoffice(ppt_path, att_dir, stem, soffice, lock)
    with lock:
        log(f"[信息] 未找到 PowerPoint/LibreOffice，将只提取文字与嵌入图片（不渲染整页幻灯片）。")
    return 0


# ---------- 文字 / 表格 / 嵌入图片提取 ----------

def extract_text_and_images(ppt_path: Path, att_dir: Path, stem: str, include_images: bool, lock, stats) -> tuple:
    """python-pptx 提取：每页的 (文字/表格/图片) 列表。返回 (页面列表, 图片数)。"""
    from pptx import Presentation
    from pptx.enum.shapes import MSO_SHAPE_TYPE

    prs = Presentation(str(ppt_path))
    saved = {}
    image_counter = 0
    n_images = 0
    pages = []
    for i, slide in enumerate(prs.slides, 1):
        items = []  # (top, left, kind, payload)
        for shape in slide.shapes:
            top = shape.top if shape.top is not None else 0
            left = shape.left if shape.left is not None else 0
            if shape.has_text_frame:
                paras = [p.text.strip() for p in shape.text_frame.paragraphs if p.text.strip()]
                if paras:
                    items.append((top, left, "text", "\n".join(paras)))
            elif getattr(shape, "has_table", False) and shape.has_table:
                rows = []
                for r in shape.table.rows:
                    rows.append([c.text.replace("\n", " ").strip() for c in r.cells])
                items.append((top, left, "table", rows))
            elif include_images and shape.shape_type == MSO_SHAPE_TYPE.PICTURE:
                try:
                    img = shape.image
                    data, ext = img.blob, str(img.ext).lower()
                except Exception:
                    continue
                if len(data) < MIN_EMBED_BYTES:
                    continue
                key = "b:" + hashlib.sha256(data).hexdigest()
                if key not in saved:
                    image_counter += 1
                    fname = f"{stem}-p{i:02d}-img-{image_counter:02d}.{ext}"
                    att_dir.mkdir(exist_ok=True)
                    try:
                        win_long_path(att_dir / fname).write_bytes(data)
                    except OSError as e:
                        with lock:
                            log(f"[警告] 图片写入失败（{ppt_path.name}）：{e}")
                        continue
                    saved[key] = fname
                    n_images += 1
                    with lock:
                        stats["images"] += 1
                items.append((top, left, "image", saved[key]))
        items.sort(key=lambda x: (x[0], x[1]))
        pages.append(items)
    return pages, n_images


def extract_text_com(ppt_path: Path):
    """旧版 .ppt 无 python-pptx 支持时，用 PowerPoint COM 提取每页文本。"""
    app = None
    try:
        import win32com.client
        import pythoncom

        pythoncom.CoInitialize()
        app = win32com.client.DispatchEx("PowerPoint.Application")
        pres = app.Presentations.Open(str(ppt_path), True, False, False)
        slides = []
        for slide in pres.Slides:
            lines = []
            for shp in slide.Shapes:
                try:
                    if shp.HasTextFrame and shp.TextFrame.HasText:
                        t = shp.TextFrame.TextRange.Text
                        if t and t.strip():
                            lines.append(t.strip())
                except Exception:
                    pass
            slides.append("\n".join(lines))
        try:
            pres.Close()
        except Exception:
            pass
        return slides
    except Exception:
        return []
    finally:
        try:
            if app:
                app.Quit()
        except Exception:
            pass
        try:
            pythoncom.CoUninitialize()
        except Exception:
            pass


# ---------- 转换单个文件 ----------

def convert_one(ppt_path: Path, args, stats: dict, lock) -> None:
    try:
        md_path = ppt_path.with_suffix(".md")

        if md_path.exists():
            head = ""
            try:
                with open(md_path, encoding="utf-8", errors="ignore") as f:
                    head = f.read(4096)
            except OSError:
                head = ""
            has_marker = MARKER in head
            if not has_marker and not args.force:
                with lock:
                    stats["conflict"] += 1
                    log(f"[跳过-保护] 已存在非本程序生成的同名 Markdown：{md_path}（如需覆盖请加 --force）")
                return
            if has_marker and not args.force and md_path.stat().st_mtime >= ppt_path.stat().st_mtime:
                with lock:
                    stats["skipped"] += 1
                return

        att_dir = ppt_path.parent / ATTACH_DIR_NAME
        stem = ppt_path.stem
        md_lines = []
        if not args.no_frontmatter:
            md_lines += [
                "---",
                f'source: "{ppt_path.name}"',
                f"converted_at: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
                "---",
                "",
            ]
        md_lines += [MARKER, ""]

        n_rendered = render_slides(ppt_path, att_dir, lock)
        is_legacy = ppt_path.suffix.lower() == ".ppt"
        n_pages = 0
        n_images = 0

        if is_legacy:
            slides_text = extract_text_com(ppt_path)
            n_pages = len(slides_text)
            for i, txt in enumerate(slides_text, 1):
                page_md = []
                if n_rendered:
                    page_md += [f"![]({ATTACH_DIR_NAME}/{stem}-slide-{i:02d}.png)", ""]
                if txt.strip():
                    page_md += [txt.strip(), ""]
                if page_md:
                    md_lines += page_md
                    if i < n_pages:
                        md_lines += ["---", ""]
            if not slides_text:
                with lock:
                    log(f"[警告] 旧版 .ppt 未能提取文字（需要 Microsoft Office；建议另存为 .pptx 后重试）")
        else:
            try:
                pages, n_images = extract_text_and_images(
                    ppt_path, att_dir, stem, include_images=(n_rendered == 0), lock=lock, stats=stats
                )
            except Exception as e:
                with lock:
                    log(f"[警告] python-pptx 提取失败（{ppt_path.name}）：{e}，尝试用 PowerPoint 提取文字")
                pages = [[("text", txt)] for txt in extract_text_com(ppt_path) if txt]
                n_images = 0
            n_pages = len(pages)
            for i, items in enumerate(pages, 1):
                page_md = []
                if n_rendered:
                    page_md += [f"![]({ATTACH_DIR_NAME}/{stem}-slide-{i:02d}.png)", ""]
                for it in items:
                    if it[2] == "text":
                        page_md += [it[3], ""]
                    elif it[2] == "table":
                        page_md += [md_table(it[3]), ""]
                    else:
                        page_md += [f"![]({ATTACH_DIR_NAME}/{it[3]})", ""]
                if page_md:
                    md_lines += page_md
                    if i < n_pages:
                        md_lines += ["---", ""]

        md_text = "\n".join(md_lines).rstrip() + "\n"
        try:
            win_long_path(md_path).write_text(md_text, encoding="utf-8")
        except OSError as e:
            with lock:
                stats["failed"] += 1
                log(f"[失败] Markdown 写入失败（{ppt_path.name}）：{e}")
            return

        with lock:
            stats["converted"] += 1
            log(f"[转换] {md_path}（{n_pages} 页，{n_images} 张嵌入图片）")
    except Exception as e:
        with lock:
            stats["failed"] += 1
            log(f"[失败] {ppt_path}：{e}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="将 PowerPoint(.ppt/.pptx) 批量转换为 Markdown（每页渲染为图片 + 文字/表格提取）",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="示例：\n"
               "  python obsidian_ppt2md.py                      # 转换当前目录下的全部 PPT\n"
               "  python obsidian_ppt2md.py \"D:\\notes\\a.pptx\"    # 转换单个文件",
    )
    parser.add_argument("target", nargs="?", default=".",
                        help="要扫描的目录，或单个 .ppt/.pptx 文件（默认当前目录）")
    parser.add_argument("--dry-run", action="store_true", help="只列出将要转换的文件，不执行任何写入")
    parser.add_argument("--force", action="store_true", help="强制重新转换，并允许覆盖同名 Markdown")
    parser.add_argument("--no-frontmatter", action="store_true", help="不写入 YAML frontmatter")
    args = parser.parse_args()

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    root = Path(args.target).resolve()
    if root.is_file():
        if root.suffix.lower() not in PPT_EXTS:
            sys.exit(f"目标不是 PPT 文件：{root}")
        files = [root]
    elif root.is_dir():
        files = []
        for p in sorted(list(root.rglob("*.ppt")) + list(root.rglob("*.pptx"))):
            rel = p.relative_to(root)
            if any(part.startswith(".") for part in rel.parts):
                continue
            if any(part.lower() == ATTACH_DIR_NAME for part in rel.parts):
                continue
            files.append(p)
    else:
        sys.exit(f"路径不存在：{root}")

    if not files:
        print(f"在 {root} 下未找到 PPT 文件。")
        return

    if args.dry_run:
        print(f"将转换 {len(files)} 个 PPT（--dry-run，未执行任何改动）：")
        for p in files:
            print(f"  {p}")
        return

    print(f"共发现 {len(files)} 个 PPT，开始转换（PowerPoint COM 不适用多线程，按顺序执行）...")
    stats = {"converted": 0, "skipped": 0, "conflict": 0, "failed": 0, "images": 0}
    lock = threading.Lock()
    for p in files:
        convert_one(p, args, stats, lock)

    print("\n完成。统计：")
    print(f"  转换成功：{stats['converted']}")
    print(f"  已跳过（未变更）：{stats['skipped']}")
    print(f"  同名冲突保护：{stats['conflict']}")
    print(f"  失败：{stats['failed']}")
    print(f"  提取嵌入图片：{stats['images']} 张")
    if stats["failed"]:
        print("存在失败项，请查看上方 [失败] 日志。")


if __name__ == "__main__":
    main()
