"use strict";

const { Plugin, Notice, PluginSettingTab, Setting, TFile } = require("obsidian");
const { execFile } = require("child_process");
const path = require("path");

const MARKER = "<!-- generated by obsidian_pdf2md -->";
const SCRIPTS = { pdf: "obsidian_pdf2md.py", ppt: "obsidian_ppt2md.py", pptx: "obsidian_ppt2md.py" };
const PIP_PACKAGES = {
  fitz: "pymupdf",
  pymupdf: "pymupdf",
  pptx: "python-pptx",
  win32com: "pywin32",
  pythoncom: "pywin32",
};

class Pdf2MdPlugin extends Plugin {
  async onload() {
    await this.loadSettings();

    this.registerEvent(
      this.app.workspace.on("file-menu", (menu, file) => {
        if (!(file instanceof TFile)) return;
        const ext = file.extension.toLowerCase();
        if (ext === "pdf") {
          menu.addItem((item) =>
            item
              .setTitle("转换为 Markdown")
              .setIcon("document")
              .onClick(() => this.convertFile(file, false))
          );
          menu.addItem((item) =>
            item
              .setTitle("转换为 Markdown（每页渲染为图片）")
              .setIcon("image")
              .onClick(() => this.convertFile(file, true))
          );
        } else if (ext === "ppt" || ext === "pptx") {
          menu.addItem((item) =>
            item
              .setTitle("转换为 Markdown（每页渲染为图片）")
              .setIcon("presentation")
              .onClick(() => this.convertFile(file, false))
          );
        }
      })
    );

    this.addCommand({
      id: "convert-active-pdf",
      name: "将当前打开的 PDF 转换为 Markdown",
      checkCallback: (checking) => {
        const f = this.app.workspace.getActiveFile();
        if (!(f instanceof TFile) || f.extension.toLowerCase() !== "pdf") return false;
        if (!checking) this.convertFile(f, false);
        return true;
      },
    });
    this.addCommand({
      id: "convert-active-pdf-page-images",
      name: "将当前打开的 PDF 转换为 Markdown（每页渲染为图片）",
      checkCallback: (checking) => {
        const f = this.app.workspace.getActiveFile();
        if (!(f instanceof TFile) || f.extension.toLowerCase() !== "pdf") return false;
        if (!checking) this.convertFile(f, true);
        return true;
      },
    });
    this.addCommand({
      id: "convert-active-ppt",
      name: "将当前打开的 PPT 转换为 Markdown",
      checkCallback: (checking) => {
        const f = this.app.workspace.getActiveFile();
        if (!(f instanceof TFile)) return false;
        const ext = f.extension.toLowerCase();
        if (ext !== "ppt" && ext !== "pptx") return false;
        if (!checking) this.convertFile(f, false);
        return true;
      },
    });

    this.addSettingTab(new Pdf2MdSettingTab(this.app, this));
  }

  onunload() {}

  async loadSettings() {
    this.settings = Object.assign(
      { pythonPath: "", ocr: false, ocrLang: "chi_sim+eng", minSize: 40 },
      await this.loadData()
    );
  }

  async saveSettings() {
    await this.saveData(this.settings);
  }

  async convertFile(file, pageImages) {
    const ext = file.extension.toLowerCase();
    const isPdf = ext === "pdf";
    const isPpt = ext === "ppt" || ext === "pptx";
    if (!isPdf && !isPpt) return;
    const kind = isPdf ? "PDF" : "PPT";

    const mdPath = file.path.replace(/\.[^.]+$/i, ".md");
    const existing = this.app.vault.getAbstractFileByPath(mdPath);
    if (existing instanceof TFile) {
      let head = "";
      try {
        head = (await this.app.vault.cachedRead(existing)).slice(0, 500);
      } catch (e) {
        head = "";
      }
      if (!head.includes(MARKER)) {
        new Notice("已存在同名 Markdown 笔记，未转换（避免覆盖）。如确需覆盖，请先重命名或删除该笔记。", 6000);
        return;
      }
    }

    let absPath = file.path;
    try {
      const adapter = this.app.vault.adapter;
      if (adapter && typeof adapter.getFullPath === "function") {
        absPath = adapter.getFullPath(file.path);
      }
    } catch (e) {
      absPath = file.path;
    }

    new Notice(kind + " 转 Markdown：开始转换…");
    const scriptPath = path.join(this.pluginDir(), SCRIPTS[ext]);
    if (!require("fs").existsSync(scriptPath)) {
      new Notice("转换失败：插件脚本缺失（" + scriptPath + "）。请重新安装插件或检查插件文件是否被移动/删除。", 10000);
      return;
    }
    const args = [scriptPath, absPath, "--force"];
    if (isPdf) {
      args.push("--workers", "1", "--min-size", String(this.settings.minSize));
      if (pageImages) args.push("--page-images");
      if (this.settings.ocr) args.push("--ocr", "--ocr-lang", this.settings.ocrLang);
    }

    const py = this.resolvePython();
    this.execPython(py.cmd, py.prefix, args, 0);
  }

  pluginDir() {
    const adapter = this.app.vault.adapter;
    let base = "";
    if (adapter && typeof adapter.getBasePath === "function") {
      try {
        base = adapter.getBasePath();
      } catch (e) {
        base = "";
      }
    }
    if (!base && adapter && typeof adapter.getFullPath === "function") {
      try {
        base = adapter.getFullPath("");
      } catch (e) {
        base = "";
      }
    }
    if (path.isAbsolute(this.manifest.dir)) return this.manifest.dir;
    return path.join(base, this.manifest.dir);
  }

  resolvePython() {
    const custom = this.settings.pythonPath.trim();
    if (custom) return { cmd: custom, prefix: this.pyPrefix(custom) };
    const bundled = path.join(this.pluginDir(), ".venv", "Scripts", "python.exe");
    if (require("fs").existsSync(bundled)) return { cmd: bundled, prefix: [] };
    return { cmd: "python", prefix: [] };
  }

  pyPrefix(p) {
    const base = path.basename(p).toLowerCase();
    return base === "py" || base === "py.exe" || base === "pyw" || base === "pyw.exe" ? ["-3"] : [];
  }

  execPython(python, prefix, args, attempt) {
    let cmd = python;
    execFile(
      cmd,
      prefix.concat(args),
      { timeout: 900000, maxBuffer: 64 * 1024 * 1024, windowsHide: true },      (err, stdout, stderr) => {
        const out = (stdout || "") + "\n" + (stderr || "");

        let pkg = null;
        const m1 = String(out).match(/No module named '?([A-Za-z0-9_.]+)'?/);
        if (m1 && PIP_PACKAGES[m1[1]]) pkg = PIP_PACKAGES[m1[1]];
        if (!pkg) {
          const m2 = String(out).match(/缺少依赖\s*([A-Za-z0-9_.]+)/);
          if (m2 && PIP_PACKAGES[m2[1].toLowerCase()]) pkg = PIP_PACKAGES[m2[1].toLowerCase()];
        }
        if (pkg && attempt === 0) {
          if (/externally managed|PEP 668|managed by uv/i.test(out)) {
            new Notice("当前 Python 禁止安装包（externally managed）。请在「设置 → PDF 转 Markdown」中把 Python 路径留空，或改填插件自带 .venv 的 python.exe。", 10000);
            return;
          }
          new Notice("首次使用：正在自动安装 " + pkg + "（约 1-2 分钟）…", 8000);
          execFile(cmd, prefix.concat(["-m", "pip", "install", pkg]), { timeout: 300000, windowsHide: true }, (e2) => {
            if (e2) {
              new Notice(pkg + " 自动安装失败，请手动在命令行运行：python -m pip install " + pkg, 10000);
              return;
            }
            this.execPython(python, prefix, args, 1);
          });
          return;
        }

        if (err && err.code === "ENOENT") {
          new Notice("未找到 Python。请在「设置 → PDF 转 Markdown」中填写 Python 路径（python.exe 的完整路径）。", 8000);
          return;
        }

        const failLine = this.findLine(out, "[失败]");
        if (failLine) {
          new Notice("转换失败：" + failLine.replace("[失败] ", ""), 10000);
          return;
        }
        const convertLine = this.findLine(out, "[转换]");
        if (convertLine) {
          new Notice("转换完成：" + convertLine.replace("[转换] ", ""), 6000);
          return;
        }
        const warnLine = this.findLine(out, "[警告]");
        if (warnLine) {
          new Notice("转换完成（含警告）：" + warnLine.replace("[警告] ", ""), 6000);
          return;
        }
        if (err) {
          const firstErr = String(stderr || err.message || "未知错误").split("\n")[0];
          new Notice("转换失败：" + firstErr, 8000);
          return;
        }
        new Notice("转换完成。", 4000);
      }
    );
  }

  findLine(text, prefix) {
    for (const line of String(text).split("\n")) {
      if (line.includes(prefix)) return line.trim();
    }
    return null;
  }
}

class Pdf2MdSettingTab extends PluginSettingTab {
  constructor(app, plugin) {
    super(app, plugin);
    this.plugin = plugin;
  }

  display() {
    const { containerEl } = this;
    containerEl.empty();
    containerEl.createEl("h2", { text: "PDF / PPT 转 Markdown 设置" });
    containerEl.createEl("p", {
      text: "右键 PDF →「转换为 Markdown」；PPT 转出的 PDF 建议选「每页渲染为图片」。右键 .ppt/.pptx →「转换为 Markdown」可直接把 PPT 转为 Markdown（每页渲染为图片 + 文字/表格提取，需安装 Microsoft Office 或 LibreOffice）。",
      attr: { style: "color: var(--text-muted);" },
    });

    new Setting(containerEl)
      .setName("Python 路径")
      .setDesc("留空时优先使用插件自带的 Python（.venv，已内置全部转换依赖）；找不到才用系统 python。也可填写完整路径覆盖，例如 C:\\Python313\\python.exe")
      .addText((text) =>
        text
          .setPlaceholder("python")
          .setValue(this.plugin.settings.pythonPath)
          .onChange(async (v) => {
            this.plugin.settings.pythonPath = v;
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName("启用 OCR")
      .setDesc("对没有文本层的扫描版/转曲 PDF 调用 tesseract 识别文字（需另行安装 tesseract 与 pytesseract，并安装中文语言包 chi_sim）")
      .addToggle((t) =>
        t.setValue(this.plugin.settings.ocr).onChange(async (v) => {
          this.plugin.settings.ocr = v;
          await this.plugin.saveSettings();
        })
      );

    new Setting(containerEl)
      .setName("OCR 语言")
      .setDesc("tesseract 语言参数，默认 chi_sim+eng（简体中文+英文）")
      .addText((t) =>
        t
          .setPlaceholder("chi_sim+eng")
          .setValue(this.plugin.settings.ocrLang)
          .onChange(async (v) => {
            this.plugin.settings.ocrLang = v;
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName("忽略过小图片")
      .setDesc("PDF：忽略宽或高小于该值的嵌入图片（单位 pt，默认 40），可减少图标/装饰图干扰")
      .addText((t) =>
        t
          .setPlaceholder("40")
          .setValue(String(this.plugin.settings.minSize))
          .onChange(async (v) => {
            const n = parseFloat(v);
            if (!isNaN(n) && n >= 0) {
              this.plugin.settings.minSize = n;
              await this.plugin.saveSettings();
            }
          })
      );
  }
}

module.exports = Pdf2MdPlugin;
