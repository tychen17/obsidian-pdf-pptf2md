#!/usr/bin/env python3
# -*- coding: utf-8 -*-





























import argparse
import hashlib
import os
import sys
import threading
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime
from pathlib import Path

try:
    import pymupdf as fitz
except ImportError:
    try:
        import fitz  # 旧版本 PyMuPDF 的模块名
    except ImportError:
        sys.exit("缺少依赖 PyMuPDF，请先执行：python -m pip install pymupdf")

MARKER = "<!-- generated by obsidian_pdf2md -->"
ATTACH_DIR_NAME = "attachments"
TEXT_BLOCK = "text"
IMAGE_BLOCK = "image"
GOOD_EXTS = {"png", "jpg", "jpeg", "gif", "bmp", "webp", "tif", "tiff"}


def win_long_path(p: Path) -> Path:
    """Windows 路径超长时使用 \\\\?\\ 前缀，规避 MAX_PATH 限制。"""
    if os.name == "nt":
        s = str(p)
        if not s.startswith("\\\\?\\") and len(s) > 240:
            return Path("\\\\?\\" + s)
    return p


def clean_text(s: str) -> str:
    """去掉提取文本中的控制字符（保留换行与制表符）。"""
    return "".join(ch if ch in "\n\t" or ord(ch) >= 32 else "" for ch in s)


def log(msg: str) -> None:
    print(msg, flush=True)


def ocr_page(page, args, lock, ocr_warned):
    """对单页渲染后调用 tesseract 做 OCR；失败时提示一次。"""
    try:
        import io
        import pytesseract
        from PIL import Image

        pix = page.get_pixmap(dpi=200)
        img = Image.open(io.BytesIO(pix.tobytes("png")))
        return pytesseract.image_to_string(img, lang=args.ocr_lang).strip()
    except Exception as e:
        with lock:
            if not ocr_warned[0]:
                ocr_warned[0] = True
                log(
                    f"[提示] OCR 不可用：{e}\n"
                    f"  请安装 tesseract（https://github.com/tesseract-ocr/tesseract）与 pytesseract，"
                    f"并确保语言包包含 {args.ocr_lang}。"
                )
        return ""


def normalize_image(data: bytes, ext: str) -> tuple:
    """非常见/不可直接渲染的图片格式尝试转成 PNG；失败则保留原格式。"""
    ext = str(ext).lower()
    if ext in GOOD_EXTS:
        return data, ext
    try:
        tmp = fitz.open(stream=data, filetype=ext)
        pix = tmp[0].get_pixmap()
        out = pix.tobytes("png")
        tmp.close()
        return out, "png"
    except Exception:
        return data, ext


def convert_one(pdf_path: Path, args, stats: dict, lock: threading.Lock, ocr_warned: list) -> None:
    try:
        md_path = pdf_path.with_suffix(".md")

        # ---- 增量与安全保护逻辑 ----
        if md_path.exists():
            head = ""
            try:
                with open(md_path, encoding="utf-8", errors="ignore") as f:
                    head = f.read(4096)
            except OSError:
                head = ""
            has_marker = MARKER in head
            if not has_marker and not args.force:
                with lock:
                    stats["conflict"] += 1
                    log(f"[跳过-保护] 已存在非本程序生成的同名 Markdown：{md_path}（如需覆盖请加 --force）")
                return
            if has_marker and not args.force and md_path.stat().st_mtime >= pdf_path.stat().st_mtime:
                with lock:
                    stats["skipped"] += 1
                return

        doc = fitz.open(pdf_path)
        if doc.needs_pass:
            doc.authenticate("")
        if doc.needs_pass:
            doc.close()
            with lock:
                stats["failed"] += 1
                log(f"[失败] 加密 PDF，无法打开：{pdf_path}")
            return

        att_dir = pdf_path.parent / ATTACH_DIR_NAME
        md_lines = []
        if not args.no_frontmatter:
            md_lines += [
                "---",
                f'source: "{pdf_path.name}"',
                f"converted_at: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
                "---",
                "",
            ]
        md_lines += [MARKER, ""]

        saved = {}  # 图片去重键 -> 已保存的文件名
        image_counter = 0
        n_images = 0
        page_count = doc.page_count

        for pno in range(page_count):
            page = doc[pno]
            try:
                blocks = page.get_text("dict", sort=True).get("blocks", [])
            except Exception:
                blocks = []

            # 按阅读顺序收集该页的文本块与图片块
            # 图片块信息统一为 ("bytes", data, ext) 或 ("xref", xref)
            page_items = []  # ("text", str) 或 ("image", info, w, h)
            for b in blocks:
                if b.get("type") == 0:
                    lines = []
                    for line in b.get("lines", []):
                        spans = line.get("spans") or []
                        if not spans:
                            continue
                        buf = spans[0].get("text", "")
                        for prev, cur in zip(spans, spans[1:]):
                            gap = cur.get("bbox", [0, 0, 0, 0])[0] - prev.get("bbox", [0, 0, 0, 0])[2]
                            buf += (" " if gap > 1.0 else "") + cur.get("text", "")
                        lines.append(buf)
                    txt = clean_text("\n".join(lines)).strip()
                    if txt:
                        page_items.append((TEXT_BLOCK, txt))
                elif b.get("type") == 1:
                    img_data = b.get("image")
                    bb = b.get("bbox") or (0, 0, 0, 0)
                    if isinstance(img_data, bytes):
                        page_items.append((IMAGE_BLOCK, ("bytes", img_data, b.get("ext", "png")),
                                           bb[2] - bb[0], bb[3] - bb[1]))
                    elif isinstance(img_data, int):
                        page_items.append((IMAGE_BLOCK, ("xref", img_data),
                                           bb[2] - bb[0], bb[3] - bb[1]))

            # 兜底：未以块形式报告的图片（Form XObject / 嵌入组等）
            placed = {it[1] for it in page_items if it[0] == IMAGE_BLOCK}
            try:
                for im in page.get_images(full=True):
                    xref = im[0]
                    if ("xref", xref) not in placed:
                        page_items.append((IMAGE_BLOCK, ("xref", xref), 0.0, 0.0))
                        placed.add(("xref", xref))
            except Exception:
                pass

            # 无文本层页面：可选 OCR
            page_has_text = any(it[0] == TEXT_BLOCK for it in page_items)
            if args.ocr and not page_has_text:
                ocr_text = ocr_page(page, args, lock, ocr_warned)
                if ocr_text:
                    page_items.insert(0, (TEXT_BLOCK, ocr_text))

            # 输出本页内容（文本 + 图片引用按原顺序）
            page_md = []
            emitted_this_page = set()
            for it in page_items:
                if it[0] == TEXT_BLOCK:
                    page_md.append(it[1])
                    page_md.append("")
                else:
                    _, info, w, h = it
                    # 统一按图片内容哈希去重（同一张图无论以字节块还是 xref 出现，只存一份）
                    if info[0] == "bytes":
                        data, ext = info[1], info[2]
                        key = hashlib.sha256(data).hexdigest()
                    else:
                        try:
                            im = doc.extract_image(info[1])
                            data, ext = im["image"], im.get("ext", "png")
                        except Exception:
                            continue
                        key = hashlib.sha256(data).hexdigest()
                    if key in saved:
                        fname = saved[key]
                        if key in emitted_this_page:
                            continue  # 本页已引用过这张图，跳过重复引用
                    else:
                        if (w and h) and (w < args.min_size or h < args.min_size):
                            continue
                        data, ext = normalize_image(data, ext)
                        image_counter += 1
                        fname = f"{pdf_path.stem}-p{pno + 1:03d}-img-{image_counter:02d}.{ext}"
                        att_dir.mkdir(exist_ok=True)
                        try:
                            win_long_path(att_dir / fname).write_bytes(data)
                        except OSError as e:
                            with lock:
                                log(f"[警告] 图片写入失败（{pdf_path.name}）：{e}")
                            continue
                        saved[key] = fname
                        n_images += 1
                        with lock:
                            stats["images"] += 1
                    page_md.append(f"![](attachments/{fname})")
                    page_md.append("")
                    emitted_this_page.add(key)

            # 可选：整页渲染为图片（适合 PPT 转出的 PDF），放在页首
            if args.page_images:
                try:
                    pix = page.get_pixmap(matrix=fitz.Matrix(2, 2), alpha=False)
                    att_dir.mkdir(exist_ok=True)
                    pfname = f"{pdf_path.stem}-page-{pno + 1:03d}.png"
                    pix.save(str(att_dir / pfname))
                    page_md.insert(0, f"![](attachments/{pfname})")
                    page_md.insert(1, "")
                except Exception as e:
                    with lock:
                        log(f"[警告] 整页渲染失败（{pdf_path.name} 第 {pno + 1} 页）：{e}")

            if page_md:
                md_lines.extend(page_md)
                if pno < page_count - 1:
                    md_lines.append("---")
                    md_lines.append("")

        md_text = "\n".join(md_lines).rstrip() + "\n"
        try:
            win_long_path(md_path).write_text(md_text, encoding="utf-8")
        except OSError as e:
            doc.close()
            with lock:
                stats["failed"] += 1
                log(f"[失败] Markdown 写入失败（{pdf_path.name}）：{e}")
            return
        doc.close()

        with lock:
            stats["converted"] += 1
            log(f"[转换] {md_path}（{page_count} 页，{n_images} 张图片）")
    except Exception as e:
        with lock:
            stats["failed"] += 1
            log(f"[失败] {pdf_path}：{e}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="将 Obsidian 知识库中的 PDF 批量转换为 Markdown（图片存入同目录 attachments/）",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="示例：\n"
               "  python obsidian_pdf2md.py                      # 转换当前目录下的全部 PDF\n"
               "  python obsidian_pdf2md.py \"D:\\notes\"           # 只转换指定目录\n"
               "  python obsidian_pdf2md.py --dry-run            # 仅预览，不写入",
    )
    parser.add_argument("target", nargs="?", default=".",
                        help="要扫描的目录，或单个 PDF 文件（默认当前目录）")
    parser.add_argument("--dry-run", action="store_true", help="只列出将要转换的 PDF，不执行任何写入")
    parser.add_argument("--force", action="store_true", help="强制重新转换，并允许覆盖同名 Markdown")
    parser.add_argument("--workers", type=int, default=4, help="并行线程数（默认 4）")
    parser.add_argument("--min-size", type=float, default=40.0, help="忽略宽或高小于该值的图片（单位 pt，默认 40）")
    parser.add_argument("--ocr", action="store_true", help="对无文本层的页面调用 tesseract OCR")
    parser.add_argument("--ocr-lang", default="chi_sim+eng", help="OCR 语言（默认 chi_sim+eng）")
    parser.add_argument("--page-images", action="store_true",
                        help="每页额外渲染成一张 PNG 放在页首（适合 PPT 转出的 PDF）")
    parser.add_argument("--no-frontmatter", action="store_true", help="不写入 YAML frontmatter")
    args = parser.parse_args()

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    root = Path(args.target).resolve()
    if root.is_file():
        if root.suffix.lower() != ".pdf":
            sys.exit(f"目标不是 PDF 文件：{root}")
        pdfs = [root]
    elif root.is_dir():
        pdfs = []
        for p in sorted(root.rglob("*.pdf")):
            rel = p.relative_to(root)
            if any(part.startswith(".") for part in rel.parts):
                continue
            if any(part.lower() == ATTACH_DIR_NAME for part in rel.parts):
                continue
            pdfs.append(p)
    else:
        sys.exit(f"路径不存在：{root}")

    if not pdfs:
        print(f"在 {root} 下未找到 PDF 文件。")
        return

    if args.dry_run:
        print(f"将转换 {len(pdfs)} 个 PDF（--dry-run，未执行任何改动）：")
        for p in pdfs:
            print(f"  {p}")
        return

    print(f"共发现 {len(pdfs)} 个 PDF，开始转换（线程数 {args.workers}）...")
    stats = {"converted": 0, "skipped": 0, "conflict": 0, "failed": 0, "images": 0}
    lock = threading.Lock()
    ocr_warned = [False]

    if args.workers <= 1:
        for p in pdfs:
            convert_one(p, args, stats, lock, ocr_warned)
    else:
        with ThreadPoolExecutor(max_workers=args.workers) as ex:
            list(ex.map(lambda p: convert_one(p, args, stats, lock, ocr_warned), pdfs))

    print("\n完成。统计：")
    print(f"  转换成功：{stats['converted']}")
    print(f"  已跳过（未变更）：{stats['skipped']}")
    print(f"  同名冲突保护：{stats['conflict']}")
    print(f"  失败：{stats['failed']}")
    print(f"  提取图片：{stats['images']} 张")
    if stats["failed"]:
        print("存在失败项，请查看上方 [失败] 日志。")


if __name__ == "__main__":
    main()
